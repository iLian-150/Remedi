# 启发式追问（v0.4.0 新增）：诊断出错误后，紧接着抛给学生一句问题，
# 引导他先自己想明白错在哪，而不是直接看解析（闭环的「追问」一环）。
#
# 模板两级：先按 (错因, 知识点) 精确/包含匹配特化模板，再按错因取通用模板，
# 最后兜底一句通用反问。无错时返回 None（不追问）。
from typing import Optional

# (错因, 知识点关键词) → 追问。知识点用包含匹配，种子知识点均可命中。
_SPECIFIC = {
    ("概念混淆", "一元一次方程"): "把 +3 从等号左边拿走时，右边要做什么，天平才不会倾斜？",
    ("概念混淆", "完全平方公式"): "(a+b)² 和 a²+b² 之间差了哪一项？把 a=1、b=2 代进去算一算，两边还相等吗？",
    ("概念混淆", "去括号"): "括号前面的系数，要乘括号里的每一项——你觉得哪一项最容易被漏掉？",
    ("计算失误", "一元一次方程"): "把你算出的答案代回原方程验算一下：左右两边相等吗？哪一步的数字最可疑？",
    ("概念混淆", "合并同类项"): "合并同类项时，只有「长得一样」的项才能合并——这一步里，哪两项其实不是同类项？",
}

# 每种错因至少一条通用模板
_GENERIC = {
    "概念混淆": "先别急着算：这一步用到的规则是什么？用一句话把规则说出来，再看看这一步是不是照着它做的。",
    "计算失误": "这一步的数字是怎么算出来的？慢慢重算一遍，或者把结果代回去验算一遍，还一样吗？",
    "审题遗漏": "回到题目本身：它到底要求什么？有没有哪个条件，在你的步骤里还没被用上？",
    "无法解析": "这一步里，哪个符号或括号让它读起来不完整？把等号和括号补完整，再读一遍试试。",
}

_DEFAULT = "再想一想：这一步为什么要这样写？你能用自己的话解释一遍吗？"


def generate_follow_up(error_type: Optional[str], knowledge_point: Optional[str]) -> Optional[str]:
    """按错因 + 知识点生成一句追问；无错因时返回 None。"""
    if not error_type:
        return None
    kp = knowledge_point or ""
    for (etype, kp_key), question in _SPECIFIC.items():
        if etype == error_type and kp_key in kp:
            return question
    return _GENERIC.get(error_type) or _DEFAULT
